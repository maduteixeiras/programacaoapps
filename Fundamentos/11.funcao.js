// Função comum com js

function sum(a,b) {
    return a + b
}

function sub(a,b) {
    return a - b
    
}

function mult(a,b) {
    return a * b
}

function div(a,b) {
    return a / b
}

const summ = sum(2,3)
const subb = sub(2,3)
const multt = mult(2,3)
const divv = div(2,3)   

console.log("Sum: ",summ)
console.log("Sub: ",subb)
console.log("Mult: ",multt)
console.log("Div: ",divv)